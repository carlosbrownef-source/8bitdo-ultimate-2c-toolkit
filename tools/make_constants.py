"""Developer tool: write u2c_customfw/firmware/stock_hashes.py from a local copy of 8BitDo's v1.09 .dat.

    make_constants.py ultimate-2c-controller-v1.09.dat

Only SHA-256 hashes are written: of each edit region of stock bank A, and of bank A with all regions zeroed.
"""
import hashlib
import sys
from pathlib import Path

from u2c_customfw.firmware import image, recipes

dat = Path(sys.argv[1]).read_bytes()
if hashlib.sha256(dat).hexdigest() != image.STOCK_DAT_SHA256:
    sys.exit("not 8BitDo's controller v1.09 .dat")
stock = dat[0x1C:]
assert hashlib.sha256(stock).hexdigest() == image.STOCK_SHA256
sha = lambda b: hashlib.sha256(b).hexdigest()
regions = {(e.addr, e.size): sha(recipes._region(stock, e)) for r in recipes.RECIPES.values() for e in r.edits}
out = Path(recipes.__file__).with_name("stock_hashes.py")
lines = ["# SPDX-License-Identifier: GPL-3.0-or-later", "# Generated by tools/make_constants.py: hashes only, no 8BitDo bytes.",
         "REGION_SHA256 = {"] + [f"    ({a:#x}, {n}): \"{h}\"," for (a, n), h in sorted(regions.items())] + [
         "}", f"REMAINDER_SHA256 = \"{sha(recipes.masked(stock))}\"", ""]
out.write_text("\n".join(lines))
print(f"wrote {out} ({len(regions)} regions)")
